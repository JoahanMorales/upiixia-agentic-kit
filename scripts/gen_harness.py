#!/usr/bin/env python3
"""Generate the Codex, Cursor and Gemini CLI subagents from the Claude Code ones (single source of truth), and the
/uak-* phase scripts for the three of them from .claude/commands.

    python3 scripts/gen_harness.py          # rewrite kit/.codex/agents, kit/.cursor/agents, kit/.gemini/agents,
                                            # kit/.agents/skills/uak-*, kit/.gemini/commands
    python3 scripts/gen_harness.py --check  # CI: exit 1 if the generated files are stale

Tiers are harness-neutral (fast / balanced / strong). Change a model in TIERS, run this, commit.
Model IDs verified on 2026-10-09: Claude docs, learn.chatgpt.com/docs/models, cursor.com/docs/subagents,
geminicli.com/docs/core/subagents. Keep this table and .uak/docs/ORCHESTRATION.md in sync.
"""
import json
import re
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parents[1] / "kit"
CLAUDE_TIER = {"haiku": "fast", "sonnet": "balanced", "opus": "strong"}
TIERS = {
    # tier:    (codex model, codex effort, cursor model, gemini model)
    "fast": ("gpt-6-luna", "low", "composer-2.5", "gemini-3-flash-preview"),
    "balanced": ("gpt-6.1-sol", "medium", "inherit", "inherit"),
    "strong": ("gpt-6-astra", "high", "claude-opus-5-5[effort=high]", "gemini-3-pro-preview"),
}
GEMINI_READ = ["read_file", "read_many_files", "grep_search", "glob", "list_directory"]
HEADER_CMD = "Generated by scripts/gen_harness.py from .claude/commands/{name}.md; edit that file, not this one."
HEADER = "Generated by scripts/gen_harness.py from .claude/agents/{name}.md; edit that file, not this one."


def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    meta = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        meta[k.strip()] = v.strip()
    return meta, m.group(2).strip() + "\n"


def readonly(meta):
    return "Edit" in meta.get("disallowedTools", "")


# Agents that never edit but must run commands (tests, the app, Verify, `uak review`, which pushes to claims).
# Cursor's readonly and Codex's read-only sandbox forbid that, so they get a normal mode and their prompt keeps
# them from editing. Why (MLB hackathon): Cursor's uak-reviewer stayed in Ask mode, could not run Verify and
# released the review lock.
EXECUTES = {"uak-runner", "uak-reviewer", "design-critic", "security-reviewer"}


def no_exec(meta):
    return readonly(meta) and meta.get("name") not in EXECUTES


def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def codex(meta, body, tier):
    model, effort, _, _ = TIERS[tier]
    effort = {"low": "low", "medium": "medium", "high": "high"}.get(meta.get("effort", ""), effort)
    sandbox = "read-only" if no_exec(meta) else "workspace-write"
    body = body.rstrip()
    return "\n".join([
        "# " + HEADER.format(name=meta["name"]),
        f"name = {toml_str(meta['name'])}",
        f"description = {toml_str(meta['description'])}",
        f"model = {toml_str(model)}",
        f"model_reasoning_effort = {toml_str(effort)}",
        f"sandbox_mode = {toml_str(sandbox)}",
        'developer_instructions = """',
        body.replace('"""', "'''"),
        '"""',
        "",
    ])


def cursor(meta, body, tier):
    model = TIERS[tier][2]
    lines = ["---", f"name: {meta['name']}", f"description: {meta['description']}", f"model: {model}"]
    if no_exec(meta):
        lines.append("readonly: true")
    lines += ["---", f"<!-- {HEADER.format(name=meta['name'])} -->", body]
    return "\n".join(lines)


def gemini(meta, body, tier):
    model = TIERS[tier][3]
    # Read-only agents with Bash keep the shell: their prompt limits it to read-only commands.
    tools = GEMINI_READ + (["run_shell_command"] if "Bash" in meta.get("tools", "") else [])
    if not readonly(meta):
        tools += ["write_file", "replace"]
    turns = meta.get("maxTurns", "15")
    lines = ["---", f"name: {meta['name']}", f"description: {meta['description']}", "kind: local",
             "tools:"] + [f"  - {t}" for t in tools] + [f"model: {model}", f"max_turns: {turns}", "timeout_mins: 10",
             "---", f"<!-- {HEADER.format(name=meta['name'])} -->", body]
    return "\n".join(lines)


NEUTRAL = [("on Haiku", "on the fast model"), ("Haiku", "fast-model"), ("Opus", "strong-model"), ("Sonnet", "balanced-model")]


def neutral(text):
    for a, b in NEUTRAL:
        text = text.replace(a, b)
    return text


# Phase scripts (.claude/commands/uak-X.md) for the other harnesses. Why (a teammate, 2026-11-10): in Codex and Cursor
# the kit's commands "were not up to date": neither had a /uak-*, and Codex no longer reads custom prompts.
#   Codex and Cursor: an Agent Skill in .agents/skills/uak-X (Codex: $uak-X or /skills; Cursor: /uak-X). Claude Code does
#     not read .agents, so /uak-X shows once there. Not model-invoked: Cursor disable-model-invocation, Codex
#     agents/openai.yaml policy.
#   Gemini CLI: .gemini/commands/uak-X.toml (/uak-X). Gemini also lists the skill above but has no switch to keep it from
#     the model, so the skill text says to run only when the user asks.
ONLY_ASKED = "Run this only when the user invokes it by name ($%s or /%s); never start it on your own."
ARGS_DEFAULT = re.compile(r"\$\{ARGUMENTS:-([^}]*)\}")


def args_for(text, skill):
    if skill:
        text = ARGS_DEFAULT.sub(lambda m: "the arguments you were given (none: %s)" % m.group(1), text)
        return text.replace("$ARGUMENTS", "<arguments>")
    text = ARGS_DEFAULT.sub(lambda m: "{{args}} (empty: %s)" % m.group(1), text)
    return text.replace("$ARGUMENTS", "{{args}}")


def phase_skill(meta, body):
    name = meta["name"]
    lines = ["---", f"name: {name}", "description: " + json.dumps(meta["description"] + " " + ONLY_ASKED % (name, name), ensure_ascii=False),
             "disable-model-invocation: true", "---", "<!-- " + HEADER_CMD.format(name=name) + " -->"]
    if meta.get("argument-hint"):
        lines.append("Arguments (what the user typed after the command, `<arguments>` below): " + meta["argument-hint"].strip('"'))
    return "\n".join(lines + [args_for(body, True)])


OPENAI_YAML = "# " + "Generated by scripts/gen_harness.py; Codex must not start a phase script on its own.\npolicy:\n  allow_implicit_invocation: false\n"


def phase_toml(meta, body):
    prompt = args_for(body, False).replace("'''", "''")
    return "\n".join(["# " + HEADER_CMD.format(name=meta["name"]), f"description = {toml_str(meta['description'])}",
                      "prompt = '''", prompt.rstrip(), "'''", ""])


def main():
    check = "--check" in sys.argv
    out = {}
    for src in sorted((KIT / ".claude/agents").glob("*.md")):
        meta, body = parse(src)
        tier = CLAUDE_TIER.get(meta.get("model", ""), "balanced")
        meta = {**meta, "description": neutral(meta["description"])}
        body = neutral(body)
        tier = CLAUDE_TIER.get(meta.get("model", ""), "balanced")
        name = meta["name"]
        out[KIT / f".codex/agents/{name}.toml"] = codex(meta, body, tier)
        out[KIT / f".cursor/agents/{name}.md"] = cursor(meta, body, tier)
        out[KIT / f".gemini/agents/{name}.md"] = gemini(meta, body, tier)
    for src in sorted((KIT / ".claude/commands").glob("uak-*.md")):
        meta, body = parse(src)
        meta = {**meta, "name": src.stem, "description": neutral(meta["description"])}
        body = neutral(body)
        out[KIT / f".agents/skills/{src.stem}/SKILL.md"] = phase_skill(meta, body)
        out[KIT / f".agents/skills/{src.stem}/agents/openai.yaml"] = OPENAI_YAML
        out[KIT / f".gemini/commands/{src.stem}.toml"] = phase_toml(meta, body)
    # A generated copy whose source is gone is stale too.
    orphans = [p for pat in (".agents/skills/uak-*/*", ".agents/skills/uak-*/agents/*", ".gemini/commands/uak-*.toml")
               for p in KIT.glob(pat) if p.is_file() and p not in out]
    stale = orphans + [p for p, t in out.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
    if check:
        for p in stale:
            print("stale:", p.relative_to(KIT.parent))
        return 1 if stale else 0
    for p in orphans:
        p.unlink()
    for p, t in out.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t, encoding="utf-8")
    print(f"wrote {len(out)} files ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
