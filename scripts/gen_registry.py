#!/usr/bin/env python3
"""gen_registry: the command registry (kit/.uak/bin/lib/commands.tsv) is the one list of uak commands.

    python3 scripts/gen_registry.py            # rewrite the generated parts
    python3 scripts/gen_registry.py --check    # exit 1 when a generated part is stale (CI, kit_lint)

At run time `uak` reads the registry for help and dispatch, and uak-mcp for which commands its tools cover. This
script writes the command index of kit/.uak/docs/CLI.md (between the registry markers) from it, and `problems()` is
what kit_lint checks: every row routes to a script or a function that exists, every MCP tool named exists, every
command has a prose row in CLI.md, every result code an engine sets is documented.
Why (v5.11, architecture review): help, two dispatch lists, CLI.md and the MCP tool list were five hand-kept copies.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BIN = ROOT / "kit/.uak/bin"
CLI = ROOT / "kit/.uak/docs/CLI.md"
BEGIN, END = "<!-- registry:begin (generated by scripts/gen_registry.py from .uak/bin/lib/commands.tsv) -->", "<!-- registry:end -->"


def rows():
    out = []
    for line in (BIN / "lib/commands.tsv").read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) != 6 or any(c == "" for c in cols):
            raise SystemExit("commands.tsv: 6 non-empty TAB-separated columns per row: %r" % line)
        out.append(dict(zip(("name", "run", "mutate", "file", "mcp", "usage"), cols)))
    return out


def index_table(rs):
    lines = [BEGIN, "| Command | Usage | Code | MCP tool |", "|---|---|---|---|"]
    for r in rs:
        if r["run"] == "-":
            continue
        code = r["file"] if r["run"] == "exec" else "lib/" + r["file"] if r["file"].endswith(".sh") else r["file"]
        tool = {"uak_cli": "`uak_cli`", "shell": "shell only (it runs a command you pass)"}.get(r["mcp"], "`%s`" % r["mcp"])
        usage = " · ".join(x["usage"] for x in rs if x["name"] == r["name"])
        lines.append("| `%s` | `%s` | `%s` | %s |" % (r["name"], usage.replace("|", "\\|").replace("`", "'"), code, tool))
    lines.append(END)
    return "\n".join(lines)


def defined(fn):
    pat = re.compile(r"^%s\(\)\s*\{" % re.escape(fn), re.M)
    for p in [BIN / "uak", BIN / "uak-coordination"] + sorted((BIN / "lib").glob("*.sh")):
        if pat.search(p.read_text(encoding="utf-8")):
            return p
    return None


def mcp_tools():
    return set(re.findall(r'^\s*\("(uak_[a-z_]+)",', (BIN / "uak-mcp").read_text(encoding="utf-8"), re.M))


def problems():
    rs, found = rows(), []
    names = [r["name"] for r in rs if r["run"] != "-"]
    for n in set(names):
        if names.count(n) > 1:
            found.append("commands.tsv · %s has two routing rows (a second row of a name has run -)" % n)
    tools = mcp_tools()
    for r in rs:
        if r["run"] == "-":
            continue
        if not r["usage"].startswith(r["name"]):
            found.append("commands.tsv · %s: its usage line starts with another word" % r["name"])
        if r["run"] == "exec":
            s = BIN / r["name"]
            if not s.is_file():
                found.append("commands.tsv · %s routes to .uak/bin/%s, which does not exist" % (r["name"], r["name"]))
        else:
            for fn in [r["run"].split(":", 1)[-1]] if r["run"] != "tx" else []:
                if not defined(fn):
                    found.append("commands.tsv · %s runs %s(), defined nowhere in the engine" % (r["name"], fn))
            if r["run"] == "tx" and r["mutate"] == "-":
                found.append("commands.tsv · %s runs a transaction but names no mutation" % r["name"])
            if r["mutate"] != "-":
                p = defined(r["mutate"])
                if not p:
                    found.append("commands.tsv · %s mutates with %s(), defined nowhere in the engine" % (r["name"], r["mutate"]))
            f = BIN / r["file"] if not r["file"].endswith(".sh") else BIN / "lib" / r["file"]
            if not f.is_file():
                found.append("commands.tsv · %s: its file %s does not exist" % (r["name"], r["file"]))
            else:
                fns = [x for x in (r["run"].split(":", 1)[-1], r["mutate"]) if x not in ("tx", "-")]
                if fns and not any(re.search(r"^%s\(\)\s*\{" % re.escape(x), f.read_text(encoding="utf-8"), re.M) for x in fns):
                    found.append("commands.tsv · %s: none of %s is in %s (the file column says where its code lives)" % (r["name"], ", ".join(fns), r["file"]))
        if r["mcp"] not in ("uak_cli", "shell") and r["mcp"] not in tools:
            found.append("commands.tsv · %s names MCP tool %s, which uak-mcp does not define" % (r["name"], r["mcp"]))
    for t in sorted(tools - {r["mcp"] for r in rs} - {"uak_cli"}):
        found.append("uak-mcp · tool %s covers no command of commands.tsv" % t)
    cli = CLI.read_text(encoding="utf-8")
    prose = cli.split(END, 1)[-1] if END in cli else cli
    for n in sorted(set(names)):
        if not re.search(r"\| `(bash \.uak/bin/)?(uak )?%s\b" % re.escape(n), prose):
            found.append("CLI.md · `%s` is in the registry but has no prose row under ## Commands" % n)
    section = cli.split("## Result codes", 1)[-1].split("\n## ", 1)[0] if "## Result codes" in cli else ""
    documented = {c for first in re.findall(r"^\| ([^|]+) \|", section, re.M) for c in re.findall(r"`([a-z-]+)`", first)}
    for p in [BIN / "uak", BIN / "uak-coordination"] + sorted((BIN / "lib").glob("*.sh")):
        code_lines = "\n".join(l for l in p.read_text(encoding="utf-8").splitlines() if not l.lstrip().startswith("#"))
        for code in sorted(set(re.findall(r"UAK_CODE=([a-z-]+) (?:conflict|die|gitfail) ", code_lines))):
            if code not in documented:
                found.append("%s · result code %s is not in CLI.md ## Result codes" % (p.relative_to(ROOT), code))
    if BEGIN not in cli or END not in cli:
        found.append("CLI.md · the generated command index is missing (run python3 scripts/gen_registry.py)")
    elif cli[cli.index(BEGIN):cli.index(END) + len(END)] != index_table(rs):
        found.append("CLI.md · the command index is stale (run python3 scripts/gen_registry.py)")
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        p = problems()
        for x in p:
            print("REGISTRY " + x)
        return 1 if p else 0
    cli = CLI.read_text(encoding="utf-8")
    table = index_table(rows())
    if BEGIN in cli and END in cli:
        cli = cli[:cli.index(BEGIN)] + table + cli[cli.index(END) + len(END):]
    else:
        cli = cli.replace("## Commands\n", "## Command index\nEvery command, its usage, where its code lives and the MCP tool that runs it.\n\n" + table + "\n\n## Commands\n", 1)
    CLI.write_text(cli, encoding="utf-8")
    print("CLI.md command index: %d commands" % sum(1 for r in rows() if r["run"] != "-"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
