#!/usr/bin/env python3
"""List every version the kit ever shipped of the files the installer places in a project (kit/.uak/settings/known-files.txt).

    python3 scripts/kit_hashes.py          # rewrite the list from the Git history
    python3 scripts/kit_hashes.py --check  # CI: exit 1 if the list is stale (needs the full history: fetch-depth 0)

`install.sh --update` replaces a project file that differs from the kit's when its Git blob hash is in this list: it is
an earlier kit version nobody edited. Only a file the team changed gets a .uak-new to merge by hand.
Why: an update from v5.0 to v5.2 left 16 .uak-new files that nobody had touched, settings.json among them, so the
v5.1/v5.2 hooks (uak away on SessionEnd, the map lens) never reached the updated project.
Variants the installer writes are listed too: CLAUDE.md as .claude/CLAUDE.md (@../AGENTS.md) and the --no-mcp configs.
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "kit/.uak/settings/known-files.txt"
# Copied whole on every install or update, or project data created once: never merged, so not listed.
SKIP = ("kit/.uak/bin/", "kit/.uak/docs/", "kit/.uak/modes/", "kit/.uak/tests/", "kit/.uak/templates/",
        "kit/.uak/VERSION", "kit/.uak/reminders.md", "kit/.uak/settings/known-files.txt")
EMPTY = "e69de29bb2d1d6434b8b29ae775ad8c2e48c5391"
# install.sh's nomcp(): the same awk/sed, so the hashes match what --no-mcp wrote.
NOMCP = {
    "toml": r"""awk '/^# The harness as native tools/{exit} {print}' | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'""",
    "json": r"""awk '/^  "mcpServers": \{/{sub(/,$/, "", prev); print prev; print "}"; done=1; exit} NR>1{print prev} {prev=$0} END{if(!done)print prev}'""",
}


def git(*args, data=None):
    return subprocess.run(["git", *args], cwd=ROOT, input=data, capture_output=True, check=True).stdout


def blob(data):
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def shipped():
    """(path, sha) of every regular file under kit/ in every commit."""
    seen = set()
    for commit in git("rev-list", "HEAD").decode().split():
        for line in git("ls-tree", "-r", commit, "--", "kit").decode().splitlines():
            meta, path = line.split("\t", 1)
            mode, kind, sha = meta.split()
            if kind == "blob" and mode in ("100644", "100755") and not path.startswith(SKIP):
                seen.add((path, sha))
    # The working tree too: the version about to be committed (in CI it is HEAD's).
    for path in git("ls-files", "--", "kit").decode().splitlines():
        p = ROOT / path
        if p.is_file() and not p.is_symlink() and not path.startswith(SKIP):
            seen.add((path, blob(p.read_bytes())))
    return seen


def main():
    files = shipped()
    hashes = {sha for _, sha in files}
    for path, sha in files:
        p = ROOT / path
        data = p.read_bytes() if p.is_file() and blob(p.read_bytes()) == sha else git("cat-file", "blob", sha)
        if path.endswith("CLAUDE.md"):
            hashes.add(blob(re.sub(rb"(?m)^@AGENTS\.md$", b"@../AGENTS.md", data)))
        ext = path.rsplit(".", 1)[-1]
        if ext in NOMCP and (b"mcpServers" in data or b"# The harness as native tools" in data):
            out = subprocess.run(["bash", "-c", NOMCP[ext]], input=data, capture_output=True, check=True).stdout
            hashes.add(blob(out))
    hashes.discard(EMPTY)
    text = "# Generated by scripts/kit_hashes.py: Git blob hashes of every kit file version ever shipped.\n" + \
           "".join(h + "\n" for h in sorted(hashes))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("kit_hashes: kit/.uak/settings/known-files.txt is stale; run python3 scripts/kit_hashes.py and commit",
                  file=sys.stderr)
            return 1
        print(f"kit_hashes: {len(hashes)} known versions, up to date")
        return 0
    OUT.write_text(text)
    print(f"kit_hashes: {len(hashes)} known versions → {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
